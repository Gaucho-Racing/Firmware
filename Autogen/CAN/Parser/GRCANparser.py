# validate()       checks the DBCs against every rule in grcan/README.md and returns the spec
# generate()       writes the spec to spec_gen.go, next to this file
# signal()         turns a cantools signal into a grcan Signal
# message_block()  renders one message
# attr()           reads a DBC attribute, or its default. Enums come back as their names
# check()          exits with an error if a rule is broken
# is_name()        tells if a name is a valid identifier
# go()             renders a field's Python value as Go
# fields()         renders a struct's set fields, leaving out zero values
# struct()         renders a one-line Go literal
# block()          renders a multi-line Go literal, aligned like gofmt
# list_block()     renders a multi-line Go slice
#
# The spec mirrors grcan/types.go: dicts keyed by field name, None for nil, '' for unset text,
# and IntEnums for ByteOrder and ValueType. Other generators import validate() and read only that.

import json
import sys
from enum import IntEnum
from itertools import groupby
from pathlib import Path

import cantools

CAN_DIR = Path(__file__).resolve().parents[1]
DBC_DIR = CAN_DIR / 'DBC'
OUT_FILE = Path(__file__).resolve().parent / 'spec_gen.go'
HEADER = '// Code generated by Parser/GRCANparser.py from DBC/*.dbc. DO NOT EDIT.\n\npackage grcan\n\n'
SCHEMA = {'Version': 1, 'Name': 'GRCAN'}
POINTERS = {'GRID': 'uint8', 'MsgID': 'uint16', 'Min': 'float64', 'Max': 'float64'}  # zero is a real value
CLASSIC_LENGTHS = set(range(9))
FD_LENGTHS = CLASSIC_LENGTHS | {12, 16, 20, 24, 32, 48, 64}


class Go(str):
    pass  # text that is already Go source


class ByteOrder(IntEnum):
    LittleEndian = 0
    BigEndian = 1


class ValueType(IntEnum):
    Unsigned = 0
    Signed = 1
    Float = 2
    ASCII = 3


def validate():
    buses, nodes, messages = {}, {}, {}
    gr_nodes, used_ids = set(), set()

    for path in sorted(DBC_DIR.glob('*.dbc')):
        try:
            db = cantools.database.load_file(path, strict=True)  # strict: signals fit and don't overlap
        except cantools.database.Error as e:
            sys.exit(f'{path.name}: {e}')

        bus = attr(db, db, 'DBName')
        fd = attr(db, db, 'BusType') == 'CAN FD'
        check(is_name(bus), path.name, f'DBName {bus!r} must be an identifier')
        check(bus not in buses, path.name, f'DBName {bus!r} is used twice')
        buses[bus] = {'ID': attr(db, db, 'GRBusID'), 'FD': fd, 'Comment': db.buses[0].comment or ''}

        for node in db.nodes:
            info = {'GRID': attr(db, node, 'GRID'), 'Comment': node.comment or ''}
            check(nodes.setdefault(node.name, info) == info, f'{path.name}: {node.name}', 'GRID or comment differs between DBCs')
        node_names = {node.name for node in db.nodes}

        for m in db.messages:
            where = f'{path.name}: {m.name}'
            name = attr(db, m, 'GRMsgName')
            msg_id = attr(db, m, 'GRMsgID')
            receivers = {r for s in m.signals for r in s.receivers}

            check(is_name(name), where, f'GRMsgName {name!r} must be an identifier')
            check(not m.is_multiplexed(), where, 'mux is not supported')
            check(len(m.senders) == 1, where, 'needs exactly one sender')
            check(len(receivers) == 1 and all(s.receivers for s in m.signals), where, 'needs one receiver, shared by all its signals')
            sender, receiver = m.senders[0], receivers.pop()
            check({sender, receiver} <= node_names, where, 'sender and receiver must be in BU_')
            check(m.is_fd == fd, where, f'frame format must match bus {bus}')
            check(m.length in (FD_LENGTHS if fd else CLASSIC_LENGTHS), where, f'length {m.length} is illegal on {bus}')
            check((bus, m.frame_id) not in used_ids, where, f'CAN ID {m.frame_id:#x} is used twice on {bus}')
            used_ids.add((bus, m.frame_id))

            if msg_id != -1:  # GR message
                sender_id, receiver_id = nodes[sender]['GRID'], nodes[receiver]['GRID']
                check(0 <= msg_id <= 0xFFF and 0 <= sender_id <= 0xFF and 0 <= receiver_id <= 0xFF, where, 'GRMsgID or GRID out of range')
                check(m.frame_id == sender_id << 20 | msg_id << 8 | receiver_id, where, 'CAN ID must be sender << 20 | GRMsgID << 8 | receiver')
                gr_nodes |= {sender, receiver}

            for s in m.signals:
                byte_aligned = s.length % 8 == 0 and s.start % 8 == 7
                check(s.byte_order == 'little_endian' or s.length == 1 or byte_aligned, where, f'{s.name}: big-endian must be byte-aligned or 1 bit')
                check(not s.is_float or s.length in (32, 64), where, f'{s.name}: floats must be 32 or 64 bits')
                plain_byte = s.length == 8 and s.start % 8 == (0 if s.byte_order == 'little_endian' else 7) and not s.is_signed and not s.is_float and (s.scale, s.offset) == (1, 0)
                check(attr(db, s, 'GRValueType') != 'ASCII' or plain_byte, where, f'{s.name}: ASCII must be 8 bits, unsigned, unscaled and byte-aligned')

            layout = {
                'MsgID': None if msg_id == -1 else msg_id,
                'Length': m.length,
                'Comment': m.comment or '',
                'Routes': [],
                'Signals': {s.name: signal(db, s) for s in m.signals},
            }
            message = messages.setdefault(name, layout)
            check({**message, 'Routes': []} == layout, where, f'differs from other routes of {name}')
            message['Routes'].append({
                'Bus': bus,
                'Sender': sender,
                'Receiver': receiver,
                'CANID': m.frame_id,
                'Extended': m.is_extended_frame,
                'BRS': fd and attr(db, m, 'CANFD_BRS') == '1',
            })

    for name, node in nodes.items():
        if name not in gr_nodes:
            node['GRID'] = None  # third-party nodes have no GRID
    for message in messages.values():
        message['Routes'].sort(key=lambda route: (route['Bus'], route['CANID']))
    return {'Schema': SCHEMA, 'Buses': buses, 'Nodes': nodes, 'Messages': messages}


def generate(spec):
    bus_entries = [(go(name), struct(bus)) for name, bus in sorted(spec['Buses'].items())]
    node_entries = [(go(name), struct(node)) for name, node in sorted(spec['Nodes'].items())]
    message_entries = [(go(name), message_block(message)) for name, message in sorted(spec['Messages'].items())]
    out = block('var CAN = Spec', [
        ('Schema', Go('Schema' + struct(spec['Schema']))),
        ('Buses', block('map[string]Bus', bus_entries, 1)),
        ('Nodes', block('map[string]Node', node_entries, 1)),
        ('Messages', block('map[string]Message', message_entries, 1)),
    ], 0)
    OUT_FILE.write_text(HEADER + out + '\n')


def signal(db, s):
    little_endian = s.byte_order == 'little_endian'
    start = s.start if little_endian or s.length == 1 else s.start - 7  # DBC gives a big-endian signal's MSB

    if attr(db, s, 'GRValueType') == 'ASCII':
        value_type = ValueType.ASCII
    elif s.is_float:
        value_type = ValueType.Float
    elif s.is_signed:
        value_type = ValueType.Signed
    else:
        value_type = ValueType.Unsigned

    return {
        'Reserved': False,  # the DBCs have no way to mark reserved signals
        'StartBit': start,
        'Length': s.length,
        'Order': ByteOrder.LittleEndian if little_endian else ByteOrder.BigEndian,
        'Type': value_type,
        'Factor': s.scale,
        'Offset': s.offset,
        'Min': s.minimum,  # cantools reads [0|0] as None
        'Max': s.maximum,
        'Unit': s.unit or '',
        'Comment': s.comment or '',
        'Values': {k: str(v) for k, v in sorted(s.choices.items())} if s.choices else None,
    }


def message_block(message):
    signal_entries = [(go(name), struct(s)) for name, s in sorted(message['Signals'].items())]
    return block('', fields({
        **message,
        'Routes': list_block('[]Route', [struct(route) for route in message['Routes']], 3),
        'Signals': block('map[string]Signal', signal_entries, 3),
    }), 2)


def attr(db, owner, name):
    definition = db.dbc.attribute_definitions.get(name)
    if name not in owner.dbc.attributes:
        return definition.default_value if definition else None
    value = owner.dbc.attributes[name].value
    return definition.choices[value] if definition and definition.type_name == 'ENUM' else value  # set enums are indices


def check(ok, where, problem):
    if not ok:
        sys.exit(f'{where}: {problem}')


def is_name(name):
    return isinstance(name, str) and name.isascii() and name.isidentifier()


def go(value, key=None):
    if key in POINTERS:
        return Go(f'Ptr[{POINTERS[key]}]({value!r})')
    if key == 'CANID':
        return Go(hex(value))
    if key == 'Values':
        return Go('map[int64]string' + struct(value))
    if isinstance(value, Go):
        return value
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, IntEnum):
        return value.name
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return repr(value)


def fields(values):
    return [(key, go(value, key)) for key, value in values.items() if (value is not None if key in POINTERS else value)]


def struct(values):
    return Go('{' + ', '.join(f'{key}: {value}' for key, value in fields(values)) + '}')


def block(head, entries, depth):
    indent = '\t' * (depth + 1)
    lines = [head + '{']
    for multiline, group in groupby(entries, key=lambda entry: '\n' in entry[1]):  # gofmt aligns runs of one-liners
        group = list(group)
        width = max(len(key) for key, _ in group)
        for key, value in group:
            gap = ' ' if multiline else ' ' * (width - len(key) + 1)
            lines.append(f'{indent}{key}:{gap}{value},')
    lines.append('\t' * depth + '}')
    return Go('\n'.join(lines))


def list_block(head, values, depth):
    indent = '\t' * (depth + 1)
    lines = [head + '{'] + [f'{indent}{value},' for value in values] + ['\t' * depth + '}']
    return Go('\n'.join(lines))


if __name__ == '__main__':
    generate(validate())
